#[inline]
fn permute_u16_12(m: u16, perm: &[u8; 12]) -> u16 {
    let mut tmp = m;
    let mut out = 0u16;
    while tmp != 0 {
        let b = tmp.trailing_zeros() as usize;
        tmp &= tmp - 1;
        out |= 1u16 << perm[b];
    }
    out
}

/// Verifică exhaustiv toate invariantele combinatorice ale ingredientelor Turán `16 + 12 + 12`
/// și returnează lista ordonată de `4,458` bilete candidate (din care pruning-ul invers
/// pe `3,838,380` extrageri păstrează exact `4,411 <= 4,500` bilete cu `0` neacoperite).
pub fn build_verified_turan_l40_5_6_4_candidates() -> Vec<u64> {
    let mut tickets: Vec<u64> = Vec::with_capacity(4_500);

    // 1. Verificare 12 x S(3, 4, 16) pe U0 (0..16) + U0_EXTRA5
    for (y, sqs) in U0_SQS16_COPIES.iter().enumerate() {
        for &qm in sqs {
            assert_eq!(qm.count_ones(), 4, "bloc S(3,4,16) invalid in copia {y}");
            tickets.push((qm as u64) | (1u64 << (16 + y)));
        }
        for a in 0..14u32 {
            for b in (a + 1)..15u32 {
                for c in (b + 1)..16u32 {
                    let tm = ((1u32 << a) | (1u32 << b) | (1u32 << c)) as u16;
                    let hits = sqs.iter().filter(|&&qm| (qm & tm) == tm).count();
                    assert_eq!(hits, 1, "S(3,4,16) copia {y} nu este Steiner exact pe tripletul ({a},{b},{c})");
                }
            }
        }
    }
    for &p5 in U0_EXTRA5 {
        assert_eq!(p5.count_ones(), 5);
        tickets.push(p5 as u64);
    }

    // 2. Verificare C(12, 4, 3) = 57 + 16 permutări pe U2 (28..40)
    let all12 = (1u16 << 12) - 1;
    for &qm in &C12_43_BLOCKS {
        assert_eq!(qm.count_ones(), 4);
        assert_eq!(qm & !all12, 0);
    }
    for a in 0..10u32 {
        for b in (a + 1)..11u32 {
            for c in (b + 1)..12u32 {
                let tm = ((1u32 << a) | (1u32 << b) | (1u32 << c)) as u16;
                assert!(C12_43_BLOCKS.iter().any(|&qm| (qm & tm) == tm), "C(12,4,3) rateaza tripletul ({a},{b},{c})");
            }
        }
    }
    for (x, perm) in U2_PERMS.iter().enumerate() {
        let mut perm_mask = 0u16;
        for &v in perm {
            assert!(v < 12);
            perm_mask |= 1u16 << v;
        }
        assert_eq!(perm_mask, all12, "permutare U2 invalida la x={x}");
        for &qm in &C12_43_BLOCKS {
            let pm = permute_u16_12(qm, perm);
            tickets.push((1u64 << x) | ((pm as u64) << 28));
        }
    }
    for &p5 in U2_EXTRA5 {
        assert_eq!(p5.count_ones(), 5);
        tickets.push((p5 as u64) << 28);
    }

    // 3. Verificare 11 x C(12, 3, 2) = 24 pe U1 (16..28) x 1-factorizarea lui K_12 pe U2 (28..40)
    let mut union_triples_u1 = BTreeSet::new();
    for (r, copy24) in C12_32_COPIES.iter().enumerate() {
        for &tm in copy24 {
            assert_eq!(tm.count_ones(), 3);
            assert_eq!(tm & !all12, 0);
            union_triples_u1.insert(tm);
        }
        for u in 0..11u32 {
            for v in (u + 1)..12u32 {
                let em = ((1u32 << u) | (1u32 << v)) as u16;
                assert!(copy24.iter().any(|&tm| (tm & em) == em), "C(12,3,2) copia {r} rateaza muchia ({u},{v})");
            }
        }
        let mut edges = [0u16; 6];
        edges[0] = (1u16 << r) | (1u16 << 11);
        for d in 1..=5usize {
            let u = (r + d) % 11;
            let v = (r + 11 - d) % 11;
            edges[d] = (1u16 << u) | (1u16 << v);
        }
        let mut factor_union = 0u16;
        for &em in &edges {
            assert_eq!(em.count_ones(), 2);
            assert_eq!(factor_union & em, 0);
            factor_union |= em;
            for &tr_m in copy24 {
                tickets.push(((tr_m as u64) << 16) | ((em as u64) << 28));
            }
        }
        assert_eq!(factor_union, all12);
    }
    assert_eq!(union_triples_u1.len(), 220, "cele 11 copii C(12,3,2) trebuie sa acopere toate cele 220 triplete din U1");

    // 4. Verificare C(12, 5, 4) = 113 pe U1 (16..28)
    for &p5 in &C12_54_BLOCKS {
        assert_eq!(p5.count_ones(), 5);
        assert_eq!(p5 & !all12, 0);
        tickets.push((p5 as u64) << 16);
    }
    for a in 0..9u32 {
        for b in (a + 1)..10u32 {
            for c in (b + 1)..11u32 {
                for d in (c + 1)..12u32 {
                    let qm = ((1u32 << a) | (1u32 << b) | (1u32 << c) | (1u32 << d)) as u16;
                    assert!(C12_54_BLOCKS.iter().any(|&p5| (p5 & qm) == qm), "C(12,5,4) rateaza cvadruplul ({a},{b},{c},{d})");
                }
            }
        }
    }

    tickets.sort_unstable();
    tickets.dedup();
    for &tk in &tickets {
        assert_eq!(tk.count_ones(), 5);
        assert!(tk < (1u64 << 40));
    }
    tickets
}

